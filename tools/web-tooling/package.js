// Turns the bundles of webpack.config.js into the suite's files: each bundle guarded so that it
// is evaluated once per executor (the harness runs the whole script on every timed run), and
// base.js with the fingerprint of each workload's result, computed here on Node, that is V8.
// Usage: node package.js <bundle dir> <suite dir>
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const [dist, out] = process.argv.slice(2);

function fingerprint(name, value) {
  // babel's result holds the transformed AST, which varies between runs; its code does not
  if (name === "babel") value = value.map(r => r.code);
  const s = JSON.stringify(value);
  if (s === undefined) return "undefined";
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619) >>> 0;
  }
  return s.length + ":" + h.toString(16);
}

const expected = {};
for (const file of fs.readdirSync(dist).filter(f => f.endsWith(".js")).sort()) {
  const bundle = fs.readFileSync(path.join(dist, file), "utf8");
  const context = vm.createContext({ print: console.log, console });
  vm.runInContext(bundle, context, { filename: file });
  const benchmark = context.__wtbBenchmark;
  expected[benchmark.name] = fingerprint(benchmark.name, benchmark.fn());
  // underscores: the harness groups files whose names share a "-" prefix (babel, babel-minify)
  const target = path.join(out, file.replace(/-/g, "_"));
  fs.writeFileSync(
    target,
    `// The "${benchmark.name}" workload of the Web Tooling Benchmark v0.5.3\n` +
      "// (https://github.com/v8/web-tooling-benchmark, BSD-3-Clause), bundled with the library and\n" +
      "// the payloads it uses, each under its own license. Generated by tools/web-tooling/build.sh.\n" +
      "if (typeof __wtbBenchmark === 'undefined') {\n" +
      bundle +
      "\n}\n"
  );
  console.log(`${benchmark.name}: ${expected[benchmark.name]}`);
}

fs.writeFileSync(
  path.join(out, "base.js"),
  fs
    .readFileSync(path.join(__dirname, "base.template.js"), "utf8")
    .replace("/*EXPECTED*/", JSON.stringify(expected, null, 2))
    .replace("/*FINGERPRINT*/", fingerprint.toString().replace(/^function fingerprint/, "function __wtbFingerprint"))
);

// Writes the suite's files from a JetStream checkout: one file per JavaScript workload of the
// default list that the other suites do not already run, holding its sources (in a function, so
// that they are loaded once per executor) and the files it preloads. A run does a tenth of
// JetStream's iterations (at least one): the harness repeats runs itself.
// Usage: node package.js <JetStream checkout> <suite dir>
const fs = require("fs");
const path = require("path");
const zlib = require("zlib");
const { listBenchmarks } = require("./list");
const [dir, out] = process.argv.slice(2);

// in the octane, sunspider and web-tooling suites, or WebAssembly, which not every engine has
function isElsewhere(benchmark) {
  return ["octane", "wtb", "wasm"].some(tag => benchmark.tags.includes(tag)) || benchmark.name.endsWith("-SP");
}

const BINARY = [".glb", ".wasm", ".bin"];

function read(file) {
  const bytes = fs.readFileSync(path.join(dir, file));
  return file.endsWith(".z") ? zlib.inflateSync(bytes) : bytes;
}

const workloads = listBenchmarks(dir).filter(b => !isElsewhere(b));
workloads.sort((a, b) => a.name.localeCompare(b.name));
for (const benchmark of workloads) {
  const data = {};
  for (const file of Object.values(benchmark.preload)) {
    const binary = BINARY.some(ext => file.replace(/\.z$/, "").endsWith(ext));
    data[file] = binary ? read(file).toString("base64") : read(file).toString("utf8");
  }
  const sources = benchmark.files.map(file => `// ${file}\n${read(file).toString("utf8")}`);
  const workload = [
    `name: ${JSON.stringify(benchmark.name)}`,
    `kind: ${JSON.stringify(benchmark.kind)}`,
    `iterations: ${Math.max(1, Math.round(benchmark.iterations / 10))}`,
    `args: ${JSON.stringify(benchmark.args)}`,
    `deterministicRandom: ${benchmark.deterministicRandom}`,
    `preload: ${JSON.stringify(benchmark.preload)}`,
    `data: ${JSON.stringify(data)}`,
  ];
  // underscores: the harness groups files whose names share a "-" prefix
  const target = path.join(out, benchmark.name.replace(/-/g, "_") + ".js");
  fs.writeFileSync(
    target,
    `// The "${benchmark.name}" workload of JetStream 3.0 (https://github.com/WebKit/JetStream,\n` +
      "// BSD-2-Clause), with the files it preloads, each under its own license. Generated by\n" +
      "// tools/jetstream3/build.sh.\n" +
      "if (typeof __js3Workload === 'undefined') {\n" +
      "var __js3Workload = {\n" +
      workload.map(line => "  " + line + ",\n").join("") +
      "  load: function () {\n" +
      sources.join("\n;\n") +
      "\n;\nreturn Benchmark;\n  }\n};\n}\n"
  );
  console.log(`${benchmark.name}: ${(fs.statSync(target).size / 1e6).toFixed(2)} MB`);
}
